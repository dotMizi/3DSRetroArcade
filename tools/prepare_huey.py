"""Build an original monochrome Huey-inspired, code-native pixel sprite.

The bitmap uses transparent cockpit/door cutouts. No aircraft photo is embedded.
"""
from pathlib import Path
W,H=64,30
mask=[[False]*W for _ in range(H)]
def rect(x,y,w,h,on=True):
    for yy in range(y,y+h):
        for xx in range(x,x+w):
            if 0<=xx<W and 0<=yy<H: mask[yy][xx]=on
def polygon(points,on=True):
    for y in range(H):
        for x in range(W):
            inside=False
            for i,(ax,ay) in enumerate(points):
                bx,by=points[i-1]
                if (ay>y+.5)!=(by>y+.5) and x+.5<(bx-ax)*(y+.5-ay)/(by-ay)+ax:
                    inside=not inside
            if inside:mask[y][x]=on
# Long tail boom, tall fin, engine cowling and the UH-1D's roomy cabin.
polygon([(3,8),(7,8),(12,15),(32,14),(37,19),(14,19),(5,17)])
polygon([(28,11),(34,8),(48,8),(52,10),(52,12)])
rect(34,7,12,2)
rect(38,4,2,4)
polygon([(28,12),(33,10),(51,10),(57,13),(61,17),(62,20),(59,23),(34,23),(28,20)])
# Cockpit glazing, cabin windows and door seams are transparent, not a second colour.
polygon([(50,12),(55,14),(59,17),(59,18),(51,18)],False)
rect(43,12,5,6,False)
rect(34,12,6,5,False)
rect(32,13,1,8,False)
rect(41,12,1,9,False)
# Skid struts and the characteristic long landing runners.
rect(36,23,2,5);rect(53,23,2,5)
rect(29,27,31,2);rect(27,26,4,2);rect(58,26,3,2)
# Small tailplane.
rect(9,19,9,1)
rows=[''.join('#' if p else '.' for p in row) for row in mask]
root=Path(__file__).resolve().parent.parent
header='''/* Original single-colour UH-1D-inspired pixel mask. Generated by tools/prepare_huey.py. */
#ifndef HUEY_SPRITE_H
#define HUEY_SPRITE_H
#define HUEY_WIDTH 64
#define HUEY_HEIGHT 30
#define HUEY_PIVOT_X 39
#define HUEY_PIVOT_Y 16
static const char hueyMask[HUEY_HEIGHT][HUEY_WIDTH+1] = {
'''+''.join('    "'+r+'",\n' for r in rows)+'''};
#endif
'''
# Front-facing cabin and skids for the centre of the yaw animation.
W=24
mask=[[False]*W for _ in range(H)]
rect(11,4,2,5)
rect(8,7,8,3)
polygon([(4,12),(7,9),(17,9),(20,12),(21,19),(18,23),(6,23),(3,19)])
rect(6,12,5,6,False)
rect(13,12,5,6,False)
rect(4,22,2,6);rect(18,22,2,6)
rect(1,27,6,2);rect(17,27,6,2)
front=[''.join('#' if p else '.' for p in row) for row in mask]
header=header.replace('#endif', '#define HUEY_FRONT_WIDTH 24\nstatic const char hueyFrontMask[HUEY_HEIGHT][HUEY_FRONT_WIDTH+1] = {\n'+''.join('    "'+r+'",\n' for r in front)+'};\n#endif')
(root/'source/huey_sprite.h').write_text(header)
